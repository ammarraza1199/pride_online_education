export function getDefaultCoursesByCategory(category) {
  return defaultCourses.filter(course => course.category.toUpperCase() === category.toUpperCase());
}

export function getDefaultCourseBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.replace(/^\//, '').toLowerCase().replace(/-admission$/, '');
  const exactSlug = slug.replace(/^\//, '').toLowerCase();

  return defaultCourses.find(c => {
    const s = c.slug.toLowerCase();
    const id = c.id.toLowerCase();
    const to = c.to ? c.to.replace(/^\//, '').toLowerCase() : '';
    const baseSlug = s.replace(/-admission$/, '');
    
    return s === exactSlug ||
      id === exactSlug ||
      to === exactSlug ||
      baseSlug === cleanSlug ||
      id.endsWith(`-${cleanSlug}`) ||
      c.title.toLowerCase().startsWith(cleanSlug);
  }) || null;
}

export function getDefaultRecentCourses(count = 8) {
  return defaultCourses.slice(0, count);
}
